def generate_report(self):
        """
        Generate and save the agent performance report.
        """
        logger.info("Generating agent performance report")

        try:
            # Prepare the output dataframe
            output_columns = [
                'call_date', 'agent_id', 'org_id', 'agent_full_name',
                'total_calls', 'unique_loans', 'connect_rate_pct',
                'avg_call_duration_min', 'presence'
            ]

            output_df = self.performance_summary_df[output_columns].copy()

            # Format columns
            output_df['connect_rate_pct'] = output_df['connect_rate_pct'].round(2)
            output_df['avg_call_duration_min'] = output_df['avg_call_duration_min'].round(2)

            # Sort by connect_rate and total_calls
            output_df = output_df.sort_values(by=['connect_rate_pct', 'total_calls'], ascending=[False, False])

            # Save to CSV
            output_file = os.path.join(self.output_path, 'agent_performance_summary.csv')
            output_df.to_csv(output_file, index=False)
            logger.info(f"Saved performance summary to {output_file}")

            # Generate a summary message
            self._generate_summary_message(output_df)

            # For Colab, also download the output file
            try:
                from google.colab import files
                files.download(output_file)
                logger.info("File download initiated for Colab")
            except:
                logger.warning("Not running in Google Colab, file download not available")

        except Exception as e:
            logger.error(f"Error generating report: {e}")
            raise

        logger.info("Report generation completed")

        return output_df
