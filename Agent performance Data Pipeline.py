def engineer_features(self):
        """
        Generate features for agent performance analysis.
        """
        logger.info("Starting feature engineering")

        # Group by agent_id, org_id, and call_date
        try:
            # Filter out rows with null agent_id, org_id, or call_date
            valid_data = self.merged_df.dropna(subset=['agent_id', 'org_id', 'call_date'])

            # Create a presence indicator (1 if login_time exists, else 0)
            valid_data['presence'] = valid_data['login_time'].notnull().astype(int)

            # Process only rows with call data for call metrics
            call_data = valid_data.dropna(subset=['call_id'])

            # Create aggregations
            agg_data = call_data.groupby(['agent_id', 'org_id', 'call_date']).agg(
                total_calls=('call_id', 'count'),
                unique_loans=('installment_id', 'nunique'),
                completed_calls=('status', lambda x: (x == 'completed').sum()),
                total_duration=('duration', 'sum')
            ).reset_index()

            # Add presence from valid_data
            presence_data = valid_data.groupby(['agent_id', 'org_id', 'call_date'])['presence'].max().reset_index()

            # Merge agg_data with presence_data
            agg_data = pd.merge(
                agg_data,
                presence_data,
                on=['agent_id', 'org_id', 'call_date'],
                how='outer'
            )

            # Handle agents in presence_data but not in agg_data (agents with presence but no calls)
            agg_data['total_calls'] = agg_data['total_calls'].fillna(0)
            agg_data['unique_loans'] = agg_data['unique_loans'].fillna(0)
            agg_data['completed_calls'] = agg_data['completed_calls'].fillna(0)
            agg_data['total_duration'] = agg_data['total_duration'].fillna(0)

            # Calculate additional metrics
            agg_data['connect_rate'] = (agg_data['completed_calls'] / agg_data['total_calls']).fillna(0)
            # Avoid division by zero for avg_call_duration_min
            agg_data['avg_call_duration_min'] = agg_data.apply(
                lambda row: (row['total_duration'] / row['total_calls'] / 60) if row['total_calls'] > 0 else 0,
                axis=1
            )

            # Get agent names from roster
            agent_names = self.agent_roster_df[['agent_id', 'org_id', 'users_first_name', 'users_last_name']]

            # Merge with agent names
            self.performance_summary_df = pd.merge(
                agg_data,
                agent_names,
                on=['agent_id', 'org_id'],
                how='left'
            )

            # Create full name column
            self.performance_summary_df['agent_full_name'] = (
                self.performance_summary_df['users_first_name'] + ' ' +
                self.performance_summary_df['users_last_name']
            )

            # Format connect_rate as percentage
            self.performance_summary_df['connect_rate_pct'] = self.performance_summary_df['connect_rate'] * 100

            logger.info(f"Created performance summary with {self.performance_summary_df.shape[0]} rows")

        except Exception as e:
            logger.error(f"Error in feature engineering: {e}")
            raise

        logger.info("Feature engineering completed")

