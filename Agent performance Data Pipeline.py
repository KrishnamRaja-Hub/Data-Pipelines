def merge_data(self):
        """
        Merge the datasets using agent_id, org_id, and call_date.
        """
        logger.info("Starting data merging")

        # Merge call_logs with agent_roster
        try:
            merged_df = pd.merge(
                self.call_logs_df,
                self.agent_roster_df,
                on=['agent_id', 'org_id'],
                how='left',
                suffixes=('', '_roster')
            )
            logger.info(f"Merged call_logs with agent_roster: {merged_df.shape[0]} rows")

            # Count missing agent roster data
            missing_roster = merged_df['users_first_name'].isnull().sum()
            if missing_roster > 0:
                logger.warning(f"Found {missing_roster} calls with missing agent roster data")
        except Exception as e:
            logger.error(f"Error merging call_logs with agent_roster: {e}")
            raise

        # Merge with disposition_summary
        try:
            self.merged_df = pd.merge(
                merged_df,
                self.disposition_summary_df,
                on=['agent_id', 'org_id', 'call_date'],
                how='outer',
                suffixes=('', '_disp')
            )
            logger.info(f"Merged with disposition_summary: {self.merged_df.shape[0]} rows")

            # Count calls without disposition
            calls_without_disp = self.merged_df[self.merged_df['call_id'].notnull() & self.merged_df['login_time'].isnull()].shape[0]
            if calls_without_disp > 0:
                logger.warning(f"Found {calls_without_disp} calls without disposition data")

            # Count dispositions without calls
            disp_without_calls = self.merged_df[self.merged_df['call_id'].isnull() & self.merged_df['login_time'].notnull()].shape[0]
            if disp_without_calls > 0:
                logger.warning(f"Found {disp_without_calls} dispositions without call data")
        except Exception as e:
            logger.error(f"Error merging with disposition_summary: {e}")
            raise

        logger.info("Data merging completed")
